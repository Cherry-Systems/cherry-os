#!/bin/sh
# Runs inside the chroot. Rebrands Debian's Calamares installer, adds a "Choose your desktop" page with
# previews, and hands a transfer picked in the live session to the new user.
set -eu
[ -d /etc/calamares ] || exit 0

ART="/usr/share/$OS_ID/artwork"
BRANDING="/etc/calamares/branding/$OS_ID"
DESC="$BRANDING/branding.desc"
MODS=/etc/calamares/modules

rm -rf "$BRANDING"
cp -a /etc/calamares/branding/debian "$BRANDING"
set_key() { sed -i "s|^\( *$1: *\).*|\1$2|" "$DESC"; }
set_key componentName "$OS_ID"
set_key productName "$OS_NAME"
set_key shortProductName "$OS_NAME"
set_key version "$OS_VERSION"
set_key shortVersion "$OS_VERSION"
set_key versionedName "\"$OS_NAME $OS_VERSION\""
set_key shortVersionedName "\"$OS_NAME $OS_VERSION\""
set_key bootloaderEntryName "\"$OS_NAME\""
set_key productUrl "https://cherry-systems.github.io/os/"
set_key SidebarBackground '"#26081e"'
set_key SidebarBackgroundCurrent '"#c81040"'
set_key SidebarText '"#fbeef3"'
set_key SidebarTextCurrent '"#ffffff"'
sed -i 's|debian-logo.png|logo.png|' "$DESC"
rm -f "$BRANDING/debian-logo.png" "$BRANDING"/slide*.png
cp "$ART/logo.png" "$BRANDING/logo.png"
cp "$ART/welcome.png" "$BRANDING/welcome.png"
cp "$ART"/slide*.png "$BRANDING/"
# The installer's icon is the cherry with a download badge, so it doesn't look like Cherry Center's.
python3 - "$ART/logo.png" /usr/share/pixmaps/install-debian.png <<'PY'
import sys
from PIL import Image, ImageDraw
im = Image.open(sys.argv[1]).convert("RGBA").resize((256, 256), Image.LANCZOS)
d = ImageDraw.Draw(im)
cx, cy, r = 186, 186, 66
d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=(255, 255, 255, 255))
d.ellipse((cx - r + 8, cy - r + 8, cx + r - 8, cy + r - 8), fill=(200, 16, 64, 255))
d.rectangle((cx - 9, cy - 38, cx + 9, cy + 4), fill="white")
d.polygon([(cx - 30, cy - 2), (cx + 30, cy - 2), (cx, cy + 28)], fill="white")
d.rectangle((cx - 34, cy + 33, cx + 34, cy + 43), fill="white")
im.save(sys.argv[2])
PY
cat > "$BRANDING/show.qml" <<'EOF'
import QtQuick 2.0;
import calamares.slideshow 1.0;

Presentation {
    id: presentation
    Timer { interval: 7000; running: presentation.activatedInCalamares; repeat: true; onTriggered: presentation.goToNextSlide() }
    Slide { Image { source: "slide1.png"; width: parent.width; height: parent.height; fillMode: Image.PreserveAspectFit } }
    Slide { Image { source: "slide2.png"; width: parent.width; height: parent.height; fillMode: Image.PreserveAspectFit } }
    Slide { Image { source: "slide3.png"; width: parent.width; height: parent.height; fillMode: Image.PreserveAspectFit } }
    Slide { Image { source: "slide4.png"; width: parent.width; height: parent.height; fillMode: Image.PreserveAspectFit } }
    Slide { Image { source: "slide5.png"; width: parent.width; height: parent.height; fillMode: Image.PreserveAspectFit } }
    function onActivate() { presentation.currentSlide = 0; }
    function onLeave() {}
}
EOF

sed -i -e "s|^branding: .*|branding: $OS_ID|" -e "s|^prompt-install: .*|prompt-install: true|" /etc/calamares/settings.conf
sed -i 's|^\(show[A-Za-z]*Url: *\)true|\1false|' $MODS/welcome.conf

# GRUB goes in EFI/cherry: Debian's GRUB updates reinstall it into the folder named after GRUB_DISTRIBUTOR's
# first word, so any other folder would leave a stale copy and a second boot entry after the first update.
# Calamares' own fallback copy is GRUB alone, which Secure Boot refuses; cherry-efi-fallback replaces it.
EFI_ID=$(echo "$OS_NAME" | tr A-Z a-z | cut -d' ' -f1)
sed -i '/^efiBootloaderId/d; /^installEFIFallback/d' $MODS/bootloader.conf
printf 'efiBootloaderId: "%s"\ninstallEFIFallback: false\n' "$EFI_ID" >> $MODS/bootloader.conf
# grub-install copies this next to shim, and shim's fallback names a boot entry it re-creates after it.
# The installer adds shim to the new system later; the diversion makes it leave this file alone.
dpkg-divert --local --rename --divert /usr/lib/shim/BOOTX64.CSV.debian --add /usr/lib/shim/BOOTX64.CSV
mkdir -p /usr/lib/shim
printf 'shimx64.efi,%s,,This is the boot entry for %s\n' "$EFI_ID" "$OS_NAME" | iconv -t UTF-16LE > /usr/lib/shim/BOOTX64.CSV

# ---- "Choose your desktop" page with previews. The live session's desktop is preselected
# (cherry-desktop live-boot rewrites "default:").
python3 - "$DEFAULT_DESKTOP" <<'PY'
import sys
sys.path.insert(0, "/usr/lib/cherry")
from cherryos.desktops import DESKTOPS
default = sys.argv[1]
# Desktops that download on request (Hyprland) aren't on the ISO, so the installer can't offer them.
ON_ISO = [d for d in DESKTOPS.values() if not d.on_demand]
lines = ["# Generated by hooks/30-installer.sh", "mode: required", "method: legacy", f"default: {default}",
         "labels:", '  step: "Desktop"', "items:"]
for d in ON_ISO:
    lines += [f"  - id: {d.id}", f'    name: "{d.label}"',
              f'    description: "{d.tagline}. {d.description} You can switch desktops any time in Cherry Center."',
              f"    screenshot: /usr/share/cherry/screens/{d.id}.png"]
open("/etc/calamares/modules/packagechooser@desktop.conf", "w").write("\n".join(lines) + "\n")

ctx = ["# Generated by hooks/30-installer.sh: set the chosen desktop as the installed default.",
       "dontChroot: false", "timeout: 30", "packagechooser_desktop:"]
for d in ON_ISO:
    ctx.append(f'  {d.id}: "cherry-desktop set-default {d.id} --user ${{USER}}"')
open("/etc/calamares/modules/contextualprocess@cherrydesktop.conf", "w").write("\n".join(ctx) + "\n")

session = DESKTOPS[default].session()
open("/etc/calamares/modules/displaymanager.conf", "w").write(
    "# Generated by hooks/30-installer.sh: Cherry OS uses GDM for every desktop.\n"
    "displaymanagers:\n  - gdm\n"
    f"defaultDesktopEnvironment:\n  executable: \"sh\"\n  desktopFile: \"{session[1] if session else 'plasma'}\"\n"
    "basicSetup: false\nsysconfigSetup: false\n")
PY

# Calamares otherwise starts on New York. Online, GeoIP finds the computer's real timezone. Ubuntu's
# lookup is used because KDE's puts places near state borders in the wrong zone (Tweed Heads, NSW came
# back as Brisbane, an hour out during daylight saving).
cat > $MODS/locale.conf <<EOF
region: "${TIMEZONE%%/*}"
zone: "${TIMEZONE#*/}"
geoip:
  style: "xml"
  url: "https://geoip.ubuntu.com/lookup"
  selector: "TimeZone"
EOF

# Files picked in the live session are restored at the new user's first login: copy the live system's
# pending transfer into the target (outside the chroot), then hand it to the new user (inside).
cat > $MODS/shellprocess@cherrytransfercopy.conf <<'EOF'
dontChroot: true
timeout: 30
script:
  - "-mkdir -p ${ROOT}/var/lib/cherry"
  - "-cp /var/lib/cherry/pending-transfer.json ${ROOT}/var/lib/cherry/pending-transfer.json"
EOF
cat > $MODS/shellprocess@cherrytransfer.conf <<'EOF'
dontChroot: false
timeout: 30
script:
  - "-cherry-move --adopt-pending ${USER}"
  - "-/usr/libexec/cherry-dual-boot-clock"
  - "-/usr/libexec/cherry-efi-fallback"
EOF
cat > /usr/libexec/cherry-efi-fallback <<EOF
#!/bin/sh
# Runs in the installed system after GRUB is set up. A computer that forgets its boot entries (firmware
# updates and settings resets do that) starts EFI/BOOT/BOOTX64.EFI instead. Make that shim, which Secure Boot
# trusts, with GRUB beside it, and GRUB's config: it only looks in EFI/debian or its own folder. Debian's
# GRUB updates then keep the shim and GRUB there current.
[ -f /boot/efi/EFI/$EFI_ID/shimx64.efi ] || exit 0
grub-install --target=x86_64-efi --efi-directory=/boot/efi --bootloader-id=$EFI_ID --force-extra-removable --no-nvram || exit 1
cp /boot/efi/EFI/$EFI_ID/grub.cfg /boot/efi/EFI/BOOT/grub.cfg
echo "grub-efi-amd64 grub2/force_efi_extra_removable boolean true" | debconf-set-selections
EOF
chmod 755 /usr/libexec/cherry-efi-fallback
# Windows keeps the hardware clock in local time; Linux in UTC would leave Windows' clock hours out.
# The live session treats it as local time: that reads a Windows PC's clock right, and it stops the
# live session writing to the hardware clock once the network sets the time (in UTC, the kernel would
# then save UTC there, and Windows would come back hours out just from trying Cherry OS).
printf '0.0 0 0.0\n0\nLOCAL\n' > /etc/adjtime
cat > /usr/libexec/cherry-dual-boot-clock <<'EOF'
#!/bin/sh
# Runs in the installed system after GRUB is set up: local time if its menu found Windows, else UTC.
if grep -qs -- '--class windows' /boot/grub/grub.cfg; then
  printf '0.0 0 0.0\n0\nLOCAL\n' > /etc/adjtime
else
  printf '0.0 0 0.0\n0\nUTC\n' > /etc/adjtime
fi
EOF
chmod 755 /usr/libexec/cherry-dual-boot-clock

python3 - <<'PY'
import re
path = "/etc/calamares/settings.conf"
text = open(path).read()
inst = ("instances:\n"
        "- id: desktop\n  module: packagechooser\n  config: packagechooser@desktop.conf\n"
        "- id: cherrydesktop\n  module: contextualprocess\n  config: contextualprocess@cherrydesktop.conf\n"
        "- id: cherrytransfercopy\n  module: shellprocess\n  config: shellprocess@cherrytransfercopy.conf\n"
        "- id: cherrytransfer\n  module: shellprocess\n  config: shellprocess@cherrytransfer.conf\n")
if re.search(r"(?m)^instances:", text):
    text = re.sub(r"(?m)^instances:\n", inst, text, count=1)
else:
    text = re.sub(r"(?m)^sequence:", inst + "\nsequence:", text, count=1)
# Desktop page right after the welcome page; desktop + transfer steps before the target is unmounted.
text = re.sub(r"(?m)^(\s*- welcome\n)", r"\1  - packagechooser@desktop\n", text, count=1)
text = re.sub(r"(?m)^(\s*)- umount", r"\1- contextualprocess@cherrydesktop\n\1- shellprocess@cherrytransfercopy\n\1- shellprocess@cherrytransfer\n\1- umount", text, count=1)
# Its hwclock step saves the time to the hardware clock in UTC, which is wrong next to Windows;
# cherry-dual-boot-clock decides instead.
text = re.sub(r"(?m)^\s*- hwclock\n", "", text, count=1)
open(path, "w").write(text)
PY

sed -i "s|^\( *\)- 'calamares-settings-debian'|&\n\1- 'calamares'|" $MODS/packages.conf
# Offline, apt only knows the packages on the ISO and stops at any other name, so only list the
# live packages that are installed.
for pkg in $(sed -n "s|^ *- '\(.*\)'\$|\1|p" $MODS/packages.conf); do
  dpkg-query -W -f='${Status}' "$pkg" 2>/dev/null | grep -q "ok installed" ||
    sed -i "/^ *- '$pkg'\$/d" $MODS/packages.conf
done

sed -i "s|^RELEASE=.*|RELEASE=\"$DEBIAN_SUITE\"|" /usr/share/calamares/helpers/calamares-sources-media
cat > /usr/share/calamares/helpers/calamares-sources-final <<'EOF'
#!/bin/sh
# The installed system keeps /etc/apt/sources.list.d/debian.sources from the live image.
CHROOT=$(mount | grep proc | grep calamares | awk '{print $3}' | sed -e "s#/proc##g")
rm -f "$CHROOT/etc/apt/sources.list"
exit 0
EOF

sed -i "s|Install Debian|Install $OS_NAME|; s|Installer for Debian Live|Installer for $OS_NAME|" \
  /usr/share/applications/calamares-install-debian.desktop /usr/bin/add-calamares-desktop-icon
# Debian's password check blocks Next for anything in its dictionary, with no way past it. Warn instead,
# with a "Require strong passwords" box people can tick.
grep -q '^allowWeakPasswords:' $MODS/users.conf ||
  printf 'allowWeakPasswords: true\nallowWeakPasswordsDefault: true\n' >> $MODS/users.conf

# Debian's dock override (installer first, no lock screen) belongs to calamares-settings-debian, which the
# installer removes, so it only applies to the live system. It loads after Cherry's 90_cherry override, so
# rebuild it from Cherry's docks with the installer in front.
python3 - <<'PY'
import re
cherry = open("/usr/share/glib-2.0/schemas/90_cherry.gschema.override").read()
out = ["# Live system only: removed with calamares-settings-debian when Cherry OS is installed."]
for section in ("org.gnome.shell", "org.cinnamon"):
    m = re.search(rf"(?ms)^\[{re.escape(section)}\]\n.*?^favorite-apps=\[(.*?)\]", cherry)
    out += [f"[{section}]", f"favorite-apps=['calamares-install-debian.desktop', {m.group(1)}]", ""]
out += ["[org.gnome.desktop.lockdown]", "disable-lock-screen=true", "",
        "[org.gnome.desktop.screensaver]", "lock-enabled=false", "",
        "[org.cinnamon.desktop.lockdown]", "disable-lock-screen=true", "",
        "[org.cinnamon.desktop.screensaver]", "lock-enabled=false", "",
        "[org.gnome.desktop.session]", "idle-delay=0", "",
        "[org.gnome.software]", "download-updates=false", "download-updates-notify=false"]
open("/usr/share/glib-2.0/schemas/96_calamares-settings-debian.gschema.override", "w").write("\n".join(out) + "\n")
PY
glib-compile-schemas /usr/share/glib-2.0/schemas

# ---- Windows that Fast Startup (or hibernation) left asleep can't be shrunk safely: Windows then fails to
# resume and finds its disk needs repairing. The installer resizes with "ntfsresize --force", which skips that
# check, so put it back (this stays on the installed system too, for GParted and KDE Partition Manager).
cat > /usr/libexec/cherry-ntfs-state <<'EOF'
#!/bin/sh
# cherry-ntfs-state DEVICE — exits like "ntfs-3g.probe --readwrite": 0 fine, 14 Windows is hibernated or
# Fast Startup left it asleep, 15 it wasn't shut down cleanly; anything else means it couldn't tell.
# The probe opens the partition read-write and ntfs-3g tidies things as it does (the root folder's
# $TXF_DATA), after which Windows wants to scan its drive. So it gets a throwaway copy-on-write view of the
# partition instead, on top of a read-only loop device: nothing it writes reaches the disk.
dev=$1
[ -b "$dev" ] || exit 1
sectors=$(blockdev --getsz "$dev") || exit 1
dir=$(mktemp -d) || exit 1
name=cherry-ntfs-state-$$
ro= cow=
cleanup() {
  dmsetup remove --retry "$name" 2>/dev/null
  [ -z "$cow" ] || losetup -d "$cow"
  [ -z "$ro" ] || losetup -d "$ro"
  rm -rf "$dir"
}
trap cleanup EXIT
truncate -s 256M "$dir/cow"
ro=$(losetup -r -f --show "$dev") || exit 1
cow=$(losetup -f --show "$dir/cow") || exit 1
echo "0 $sectors snapshot $ro $cow N 8" | dmsetup create "$name" || exit 1
ntfs-3g.probe --readwrite "/dev/mapper/$name" >/dev/null 2>&1
exit $?
EOF
chmod 755 /usr/libexec/cherry-ntfs-state
dpkg-divert --local --rename --divert /usr/sbin/ntfsresize.real --add /usr/sbin/ntfsresize
cat > /usr/sbin/ntfsresize <<'EOF'
#!/bin/sh
# Cherry OS: refuses to resize a Windows partition that didn't fully shut down, even with --force.
# Only looking at it (--info, --no-action) is still allowed.
# The device isn't always the last argument (KPMcore: --force DEVICE --size N).
dev=
for a; do [ -b "$a" ] && dev=$a; done
case " $* " in
  *" --info "*|*" -i "*|*" --no-action "*|*" -n "*|*" --help "*|*" -h "*|*" --version "*|*" -V "*) ;;
  *)
    [ -n "$dev" ] || exec /usr/sbin/ntfsresize.real "$@"
    /usr/libexec/cherry-ntfs-state "$dev"
    case $? in 14|15)
      echo "Windows on $dev didn't fully shut down (Fast Startup is on, or it's hibernated), so resizing it" \
           "now would damage it. Start Windows, hold Shift while you click Shut down, then try again." >&2
      exit 1 ;;
    esac
    /usr/sbin/ntfsresize.real "$@"
    rc=$?
    # A resize marks the partition for checking. Windows 10 and 11 no longer check it as they start: they
    # report the drive as needing repair and later ask to restart and fix it. So once ntfsresize's own full
    # consistency check passes, clear the mark (if the check fails, it stays, and Windows checks).
    if [ $rc -eq 0 ] && /usr/sbin/ntfsresize.real --info --force --no-progress-bar "$dev" >/dev/null 2>&1; then
      ntfsfix --clear-dirty "$dev" >/dev/null 2>&1
    fi
    exit $rc ;;
esac
exec /usr/sbin/ntfsresize.real "$@"
EOF
chmod 755 /usr/sbin/ntfsresize

# ...and say so before the installer opens, rather than when it fails to make room.
cat > /usr/libexec/cherry-install-check <<'EOF'
#!/usr/bin/python3
"""Runs before the installer: if Windows on this computer is asleep, explain how to shut it down properly.
Exits 10 when the person chose not to install yet; anything else opens the installer."""
import json
import subprocess
import sys

sys.path.insert(0, "/usr/lib/cherry")


def sleeping_windows():
    tree = subprocess.run(["lsblk", "-J", "-p", "-o", "NAME,FSTYPE"], capture_output=True, text=True).stdout
    found = []

    def walk(devices):
        for d in devices or []:
            if d.get("fstype") == "ntfs" and subprocess.run(
                    ["sudo", "-n", "/usr/libexec/cherry-ntfs-state", d["name"]], capture_output=True).returncode in (14, 15):
                found.append(d["name"])
            walk(d.get("children"))
    walk(json.loads(tree or "{}").get("blockdevices"))
    return found


if not sleeping_windows():
    sys.exit(0)

from cherryos.ui import Adw, Gtk, apply_css, hbox, identify, pill, status_page  # noqa: E402

# No application ID, so the window takes the installer's menu entry name and icon in the taskbar.
identify("calamares-install-debian", "Install Cherry OS", "install-debian")
app = Adw.Application()
answer = []


def activate(app):
    apply_css()
    win = Adw.ApplicationWindow(application=app, title="Install Cherry OS", default_width=620, default_height=560)

    def done(response):
        answer.append(response)
        win.close()
    buttons = hbox(12, pill("Not now", False, lambda: done("cancel")), pill("Carry on", True, lambda: done("continue")),
                   halign=Gtk.Align.CENTER)
    page = status_page(
        "dialog-warning-symbolic", "Windows is still asleep",
        "Windows didn't fully shut down last time, because its Fast Startup feature is on. Cherry OS can't "
        "safely make room next to it like this.\n\n"
        "To keep Windows, start it, then hold Shift while you click Shut down. (Turning off Fast Startup in "
        "Control Panel → Power Options stops this happening again.) Then start Cherry OS from the USB stick again.\n\n"
        "If you're replacing Windows, or installing on another disk, you can carry on.", buttons)
    view = Adw.ToolbarView()
    view.add_top_bar(Adw.HeaderBar())
    view.set_content(page)
    win.set_content(view)
    win.present()


app.connect("activate", activate)
app.run([sys.argv[0]])
sys.exit(0 if answer == ["continue"] else 10)
EOF
chmod 755 /usr/libexec/cherry-install-check
sed -i 's|^sudo mv /etc/fstab /etc/fstab.orig.calamares|/usr/libexec/cherry-install-check \|\| [ $? -ne 10 ] \|\| exit 0\n&|' \
  /usr/bin/calamares-install-debian
grep -q cherry-install-check /usr/bin/calamares-install-debian

# Debian's script ends in a broken preload loop ("): do", "ionice -C") that errors at every login.
sed -i -e 's/ionice -C Idle/ionice -c 3/' -e "s/}'): do\$/}'); do/" /usr/bin/add-calamares-desktop-icon
